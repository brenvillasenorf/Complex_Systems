"""# Boxcounting

2. Programar y utilizar un algoritmo de "conteo de cajas" (box counting) para encontrar la dimensión fractal del triángulo graficado arriba.
"""

# Implementamos el algortimo de box counting

def count_occup_boxes(grid, e):
    """
    Cuenta la cantidad de cajas de lado e que cubren el grafo.
    e : lado de la caja (box size)
    """
    rows, cols = grid.shape
    occup_count = 0
    for r in range(0, rows, e):
        for c in range(0, cols, e):
            # Checar si la celda está ocupada
            if np.any(grid[r:r+e, c:c+e] > 0):
                occup_count += 1
    return occup_count

# Definimos un rango de tamaños para las cajas (potencias de 2, pues haremos un log-log)
e_s = [2**i for i in range(int(np.log2(min(grid.shape))))]

# Calculamos la cantidad de cajas para cada tamaño
occupied_counts = [count_occup_boxes(grid, box_size) for box_size in e_s]

# Quitamos los tamaños en los que no hubieron cajas ocupadas
valid_indices = [i for i, count in enumerate(occupied_counts) if count > 0]
valid_e_s = [e_s[i] for i in valid_indices]
valid_occup_counts = [occupied_counts[i] for i in valid_indices]


# Calculate log-log values
log_box_sizes = np.log(1 / np.array(valid_e_s))
log_occup_counts = np.log(np.array(valid_occup_counts))

# Realizamos un ajuste lineal para calcular la dimensión fractal que es D = log(N)/log(1/e)
slope, intercept = np.polyfit(log_box_sizes, log_occup_counts, 1)
fractal_dimension = slope

print(f"Calculated Fractal Dimension: {fractal_dimension}")

# Graficamos la gráfica log-log
plt.figure(figsize=(8, 6))
plt.plot(log_box_sizes, log_occup_counts, 'o', label='Datos')
plt.plot(log_box_sizes, slope * log_box_sizes + intercept, 'r-', label=f'Ajuste Lineal (Dimension = {fractal_dimension:.2f})')
plt.xlabel('log(1 / e)')
plt.ylabel('log(N(e))')
plt.title('Método de Box-Counting para la Dimensión Fractal')
plt.legend()
plt.grid(True)
plt.show()

