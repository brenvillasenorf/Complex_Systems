  lista_x = []
  lista_y = []
  # Realizamos la iteración
  for i in range(N):
    # obtenemos un vertice aleatorio
    rx, ry = random.choice(v)
    # calculamos el punto medio entre el vértice y el punto anterior
    x = (rx + x)/2
    y = (ry + y)/2
    # guardamos los puntos en las listas
    lista_x.append(x)
    lista_y.append(y)
  return lista_x, lista_y

