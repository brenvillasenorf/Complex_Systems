# creamos la función de la ecuacion de lorenz
def lorenz(x, y, z, sigma, rho, beta, delta):
    dx = sigma * (y - x)
    dy = x * (rho - z) - y
    dz = x * y - beta * z
    x = x + delta*dx
    y = y + delta*dy
    z = z + delta*dz
    return x, y, z

