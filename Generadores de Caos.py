"""## Mapeo de Henón"""

def henon_map(x, y, a, b, N):
    series_x = []
    series_y = []
    for _ in range(N):
        x_new = 1 - a * x**2 + y
        y_new = b * x
        x, y = x_new, y_new
        series_x.append(x)
        series_y.append(y)
    return series_x, series_y

